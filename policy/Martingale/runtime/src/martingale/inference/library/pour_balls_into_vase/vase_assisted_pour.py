"""
Use ``fit_rim`` on actual visible pixels in two calibrated views; inspect its
``rim_overlay`` before ``make_reference``. Plans
use an explicitly declared rigid-grip prediction, never fake fresh landmarks.
All coordinates are world metres, image coordinates (row,column), angles
in degrees and quaternions wxyz. Plans never execute themselves or end an episode."""
import hashlib
import json
import math
import numpy as np
from scipy.optimize import least_squares
from scipy.spatial.transform import Rotation
try:
    from . import assistive_vision as vision
except ImportError:
    from . import assistive_vision as vision

def _unit(x):
    return vision._unit(x)

def project(meta, points):
    """Project world Nx3 points to Nx2 original-image row/column coordinates."""
    e = np.asarray(meta['extrinsic_matrix'])
    k = np.asarray(meta['intrinsic_matrix'])
    camera = (np.asarray(points) - e[:3, 3]) @ e[:3, :3] * [1, -1, -1]
    if np.any(camera[:, 2] <= 0):
        raise ValueError('Geometry behind camera; get another view')
    p = camera @ k.T
    return np.stack([p[:, 1] / p[:, 2], p[:, 0] / p[:, 2]], axis=1)

def _ring(center, radius, axis, samples=360):
    axis = _unit(axis)
    basis = np.eye(3)[np.argmin(abs(axis))]
    u = _unit(np.cross(axis, basis))
    v = np.cross(axis, u)
    a = np.linspace(0, 2 * np.pi, samples, endpoint=False)
    return np.asarray(center) + radius * (np.cos(a)[:, None] * u + np.sin(a)[:, None] * v)

def fit_rim(packet, annotations, *, initial, bounds, max_rms_px=4.0, max_point_px=7.0):
    """Fit a circular rim to independent visible boundary pixels in >=2 views.

    annotations: {camera: {'pixels_rc': [[r,c],...], 'image_sha256': str,
    'origin': 'observed_rgb'}}. At least six points/view, distributed on visible
    arcs; never generated by projecting an old estimate. initial/bounds contain
    [cx,cy,cz,radius,axis_x,axis_y,axis_z]. Obtain coarse bounds from locate
    or triangulation, NOT a task/layout constant. Axis sign is resolved by caller
    from the cup opening; circle images alone cannot resolve front/back.

    Returns candidate geometry, exact image provenance and pixel residuals.
    Low residual is NOT proof of correct landmark identity or unique geometry.
    Sparse arcs/occlusion require another view. Invalid inputs return recovery.
    """
    try:
        if len(annotations) < 2:
            raise ValueError('Need two views')
        data = {}
        for cam, a in annotations.items():
            if a.get('origin') != 'observed_rgb':
                raise ValueError('Independent observed pixels required')
            if a.get('image_sha256') != packet['image_sha256s'][cam]:
                raise ValueError('Image hash mismatch')
            p = np.asarray(a['pixels_rc'], float)
            h, w = packet['images'][cam].shape[:2]
            if p.ndim != 2 or p.shape[1] != 2 or len(p) < 6 or (not np.isfinite(p).all()):
                raise ValueError('Need six finite rim pixels/view')
            if np.any(p < 0) or np.any(p[:, 0] >= h) or np.any(p[:, 1] >= w):
                raise ValueError('Pixel outside image')
            data[cam] = p

        def residual(x):
            pts = _ring(x[:3], x[3], x[4:7])
            out = []
            for cam, p in data.items():
                projected = project(packet['calibration'][cam], pts)
                out.extend(np.sqrt(((p[:, None, :] - projected[None, :, :]) ** 2).sum(2)).min(1))
            return out
        fit = least_squares(residual, initial, bounds=bounds, diff_step=0.0001, max_nfev=250)
        r = np.asarray(residual(fit.x))
        rms = float(np.sqrt(np.mean(r * r)))
        status = 'candidate_for_visual_review' if rms <= max_rms_px and max(r) <= max_point_px else 'return_to_agent'
        return dict(status=status, center_xyz=fit.x[:3].tolist(), radius_m=float(fit.x[3]), axis=_unit(fit.x[4:7]).tolist(), rms_px=rms, max_residual_px=float(max(r)), residuals_px=r.tolist(), annotations=annotations, source_step=packet['step'], source_action_count=packet['action_count'], source_image_sha256s={c: packet['image_sha256s'][c] for c in data}, geometry_kind='image-fitted circular rim candidate', pose_verified=False)
    except (ValueError, KeyError, TypeError) as exc:
        return dict(status='return_to_agent', reason=str(exc), pose_verified=False)

def rim_overlay(packet, evidence, camera):
    """Return RGB overlay: observed points green, projected fit cyan. No motion.

    Cyan points are predictions; green points are actual caller-selected pixels.
    Only visible predictions are drawn; clipped points are never measurements.
    """
    from PIL import Image, ImageDraw
    if packet['image_sha256s'][camera] != evidence['source_image_sha256s'][camera]:
        raise ValueError('Stale overlay')
    im = Image.fromarray(np.asarray(packet['images'][camera], dtype=np.uint8))
    draw = ImageDraw.Draw(im)
    for r, c in evidence['annotations'][camera]['pixels_rc']:
        draw.ellipse((c - 3, r - 3, c + 3, r + 3), fill='lime')
    points = project(packet['calibration'][camera], _ring(evidence['center_xyz'], evidence['radius_m'], evidence['axis']))
    for r, c in points:
        if 0 <= r < im.height and 0 <= c < im.width:
            draw.point((float(c), float(r)), fill='cyan')
    return im

def make_reference(packet, cup, vase, *, arm, reviewed_image_hashes):
    """Freeze visually reviewed cup-in-grip geometry and static vase observation.

    Call after reviewing actual overlays in a PREVIOUS cell response. Preserve
    vase evidence as a static prior; remeasure if moved. No hardcoded locations.
    Refit cup if slipping or discrepancy appears. This review is agent judgment,
    not independent sensor certification. Returns a pure serializable reference.
    """
    hashes = {**cup['source_image_sha256s'], **vase['source_image_sha256s']}
    if reviewed_image_hashes != hashes or any((packet['image_sha256s'].get(k) != v for k, v in hashes.items())):
        raise ValueError('Review must match current images')
    if cup['source_step'] != packet['step'] or cup['source_action_count'] != packet['action_count']:
        raise ValueError('Cup observation is stale')
    if any((e['status'] != 'candidate_for_visual_review' for e in [cup, vase])):
        raise ValueError('Resolve uncertain geometry first')
    r = vision._rotation(packet['arms'][arm]['eef_quat'])
    tcp = np.asarray(packet['arms'][arm]['tcp_pos'])
    d = np.asarray(vase['center_xyz']) - cup['center_xyz']
    d[2] = 0
    return dict(arm=arm, local_rim=(r.T @ (np.asarray(cup['center_xyz']) - tcp)).tolist(), local_axis=(r.T @ cup['axis']).tolist(), radius_m=cup['radius_m'], mouth_xyz=vase['center_xyz'], direction=_unit(d).tolist(), observation_hashes=hashes, source_step=packet['step'], geometry_kind='reviewed reference; future propagation is prediction')

def _rotation_between(axis, target, limit=15.0):
    a = _unit(axis)
    b = _unit(target)
    angle = math.degrees(math.acos(float(np.clip(a @ b, -1, 1))))
    cross = np.cross(a, b)
    if np.linalg.norm(cross) < 1e-08:
        if angle < 1e-05:
            return (np.eye(3), angle)
        cross = np.cross(a, np.eye(3)[np.argmin(abs(a))])
    return (Rotation.from_rotvec(_unit(cross) * math.radians(min(angle, limit))).as_matrix(), angle)

def _plan(robo, packet, ref, xyz, rotation, kind):
    if robo.state().step != packet['step'] or robo.action_count() != packet['action_count']:
        return dict(status='return_to_agent', reason='Stale packet')
    angles = vision._angles(rotation)
    pose = dict(xyz=np.asarray(xyz).tolist(), **angles)
    preview = robo.preview_move(pose['xyz'], arm=ref['arm'], **angles, path='line')
    result = dict(status='review_required' if preview['reachable'] else 'return_to_agent', arm=ref['arm'], pose=pose, preview=preview, source_step=packet['step'], source_action_count=packet['action_count'], image_sha256s=packet['image_sha256s'], kind=kind, geometry_kind='rigid-grip prediction', fresh_visual_measurement=False, collision_checked=False)
    result['review_id'] = hashlib.sha256(json.dumps(result, sort_keys=True).encode()).hexdigest()
    return result

def preview_pour(robo, packet, reference, *, tilt_degrees, clearance_m, upstream_m=0.012):
    """Preview <=15deg lip-anchored tilt; no motion. Review each bounded segment.

    Clearance is above observed mouth, not guaranteed achieved gap. Choose from
    actual finger/cup clearance; one case used25mm late,50mm initially.
    Keep original horizontal pour direction fixed. Beyond90deg clamp horizontal
    rim compensation to avoid advancing the cup past the vessel center.
    """
    if not 0 <= tilt_degrees <= 135 or not 0 < clearance_m < 0.15 or (not 0 <= upstream_m < 0.05):
        raise ValueError('Invalid pour request')
    ref = reference
    s = packet['arms'][ref['arm']]
    r = vision._rotation(s['eef_quat'])
    d = np.array(ref['direction'])
    theta = math.radians(tilt_degrees)
    target = math.cos(theta) * np.array([0, 0, 1]) + math.sin(theta) * d
    delta, angle = _rotation_between(r @ ref['local_axis'], target)
    if angle > 15.5:
        return dict(status='return_to_agent', reason='Use smaller tilt increment', requested_rotation_deg=angle)
    rr = delta @ r
    lip = np.asarray(ref['mouth_xyz']) + [0, 0, clearance_m] - upstream_m * d
    rim = lip - ref['radius_m'] * (max(math.cos(theta), 0) * d - math.sin(theta) * np.array([0, 0, 1]))
    return _plan(robo, packet, ref, rim - rr @ ref['local_rim'], rr, 'pour')

def preview_axial_turn(robo, packet, reference, *, degrees):
    """Preview grip-approach rotation around cup axis, retaining predicted rim.

    FIRST lift/retreat into visually clear space. One case used+60deg;
    choose sign/amount from current fingers, vase, free arm and IK, not layout ID.
    This changes finger approach without intentionally changing cup tilt.
    """
    if not 0 < abs(degrees) <= 90:
        raise ValueError('Bound axial turn to90degrees')
    ref = reference
    s = packet['arms'][ref['arm']]
    r = vision._rotation(s['eef_quat'])
    axis = _unit(r @ ref['local_axis'])
    rr = Rotation.from_rotvec(axis * math.radians(degrees)).as_matrix() @ r
    rim = np.asarray(s['tcp_pos']) + r @ ref['local_rim']
    return _plan(robo, packet, ref, rim - rr @ ref['local_rim'], rr, 'clear-space axial turn')

def preview_upright(robo, packet, reference):
    """Preview one <=15deg upright correction about current predicted rim.

    Lift clear of vessel first. Reobserve actual cup orientation before setdown;
    reaching commanded wrist orientation does not prove cup alignment.
    """
    ref = reference
    s = packet['arms'][ref['arm']]
    r = vision._rotation(s['eef_quat'])
    delta, angle = _rotation_between(r @ ref['local_axis'], [0, 0, 1])
    rr = delta @ r
    rim = np.asarray(s['tcp_pos']) + r @ ref['local_rim']
    plan = _plan(robo, packet, ref, rim - rr @ ref['local_rim'], rr, 'upright')
    plan['remaining_predicted_angle_deg'] = angle
    return plan

def execute_reviewed(robo, plan, *, review_id, clearance_note):
    """Execute one previously visually reviewed plan; return control on problems.

    review_id binds the exact proposal shown to the agent; clearance_note must
    describe the inspected path. This is an agent decision, not collision sensing.
    Never execute merely because preview IK succeeded. Reobserve after this call.
    """
    if plan.get('status') != 'review_required' or review_id != plan.get('review_id') or (not clearance_note.strip()):
        return dict(status='return_to_agent', reason='Missing exact visual review')
    if robo.state().step != plan['source_step'] or robo.action_count() != plan['source_action_count']:
        return dict(status='return_to_agent', reason='Plan stale; reobserve')
    p = plan['pose']
    reply = robo.move_to(p['xyz'], arm=plan['arm'], pitch=p['pitch'], yaw=p['yaw'], roll=p['roll'], gripper=robo.CLOSE, path='line')
    return dict(status='return_to_agent' if reply.blocked or reply.ik_error or (not reply.reached) else 'reobserve', reply=reply, task_success_claim=False)

def settle(robo, arm, *, actions=8):
    """Hold current closed-grip pose for1..10 actions, then reobserve.

    Wall-clock/API waiting does not advance physics. Stop this primitive on a
    blocked move and return to the agent; never end the episode. Inspect ball flow
    after settling. Caller must first review that the current pose is safe.
    """
    if not isinstance(actions, int) or not 1 <= actions <= 10:
        raise ValueError('Settle uses1..10actions')
    s = robo.state().arm(arm)
    replies = []
    for _ in range(actions):
        r = robo.move_to(s.tcp_pos, arm=arm, pitch=s.pitch, yaw=s.yaw, roll=s.roll, gripper=robo.CLOSE, path='line')
        replies.append(r)
        if r.blocked or r.ik_error or (not r.reached) or r.truncated:
            return dict(status='return_to_agent', replies=replies)
    return dict(status='reobserve', replies=replies)
