#!/usr/bin/env python3
"""Write a private config.env; credentials stay in an external key file."""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import shlex
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]


def split_api_base(value: str) -> tuple[str, str]:
    url = urlsplit(value)
    if (url.scheme not in ("http", "https") or not url.hostname
            or url.username is not None or url.password is not None
            or url.query or url.fragment or any(c.isspace() for c in value)):
        raise ValueError("Use an HTTP(S) API base URL without credentials, query, or fragment")
    path = url.path.rstrip("/")
    if path.endswith("/chat/completions"):
        raise ValueError("Use the API base, e.g. https://api.example.com/v1, without /chat/completions")
    # A slash represents the origin root; an empty value would trigger the launcher's /v1 default.
    return f"{url.scheme}://{url.netloc}", path or "/"


def load_settings(path: Path) -> dict:
    settings = json.loads(path.read_text())
    defaults = json.loads((ROOT / "configs/model_api.example.json").read_text())
    if settings.keys() != defaults.keys():
        raise ValueError("Model config must have exactly the keys in configs/model_api.example.json")
    for key, default in defaults.items():
        value = settings[key]
        if isinstance(default, float):
            valid = type(value) in (float, int)
        else:
            valid = type(value) is type(default)
        if not valid:
            raise ValueError(f"Invalid type for model setting: {key}")
    for key in ("max_tokens", "max_turns", "request_timeout_s"):
        if settings[key] <= 0:
            raise ValueError(f"{key} must be positive")
    if settings["reasoning_effort"] != "max":
        raise ValueError("This runner uses reasoning_effort=max")
    if not settings["model"].strip():
        raise ValueError("Model name must not be empty")
    if settings["skills"]:
        raise ValueError("This variant requires skills=false")
    return settings


def environment(settings: dict, *, repo: Path, isaac_python: Path, api_base: str,
                key_file: Path, sam3_url: str, sim_cache: str = "", tmp_dir: str = "") -> dict[str, str]:
    origin, prefix = split_api_base(api_base)
    split_api_base(sam3_url)
    return {
        "ROBODOJO_REPO": str(repo), "ISAAC_PYTHON": str(isaac_python),
        "MODEL_UPSTREAM": origin, "MODEL_BASE_PATH": prefix,
        "MODEL_KEY_FILE": str(key_file), "MODEL": settings["model"],
        "HEXASHELL_REASONING_EFFORT": settings["reasoning_effort"],
        "HEXASHELL_CHAT_TEMPLATE_KWARGS": json.dumps(settings["chat_template_kwargs"], separators=(",", ":")),
        "HEXASHELL_MAX_TOKENS": str(settings["max_tokens"]),
        "HEXASHELL_TEMPERATURE": str(settings["temperature"]),
        "HEXASHELL_STREAM": str(int(settings["stream"])),
        "HEXASHELL_HISTORY_REASONING": str(int(settings["history_reasoning"])),
        "HEXASHELL_MAX_TURNS": str(settings["max_turns"]),
        "HEXASHELL_REQUEST_TIMEOUT_S": str(settings["request_timeout_s"]),
        "HEXASHELL_SKILLS": "0",
        "HEXASHELL_SAM3_URL": sam3_url.rstrip("/"), "HEXASHELL_MOTION": "v2",
        "ROBOSHELL_RECIPE": "0", "ROBOSHELL_NOTES": "0", "ROBOSHELL_PROFILE": "open", "IMAGE": "joyai-vl/agent:preview",
        "BASE_IMAGE": "python:3.11-slim-bookworm",
        "SIM_CACHE": sim_cache, "TMPDIR": tmp_dir,
    }


def write_config(path: Path, values: dict[str, str]) -> None:
    # Exclusive creation avoids accidentally changing a running evaluation.
    content = "# Generated by the JoyAI-VL evaluation setup. Keep this machine configuration private.\n"
    content += "".join(f"{key}={shlex.quote(value)}\n" for key, value in values.items())
    descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(descriptor, "w") as stream:
        stream.write(content)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--robodojo-repo", required=True, type=Path)
    parser.add_argument("--isaac-python", required=True, type=Path)
    parser.add_argument("--api-base", required=True)
    parser.add_argument("--key-file", required=True, type=Path)
    parser.add_argument("--model", help="Model ID accepted by your serving endpoint")
    parser.add_argument("--model-config", type=Path, default=ROOT / "configs/model_api.example.json")
    parser.add_argument("--sam3-url", default="http://127.0.0.1:18300")
    parser.add_argument("--sim-cache", default="")
    parser.add_argument("--tmp-dir", default="")
    args = parser.parse_args()
    try:
        repo = args.robodojo_repo.expanduser().resolve()
        policy = repo / "XPolicyLab/policy/JoyAI_VL"
        if not (policy / "eval.sh").is_file():
            raise ValueError("Install the policy first with tools/install_policy.py")
        python = args.isaac_python.expanduser().resolve()
        if not python.is_file() or not os.access(python, os.X_OK):
            raise ValueError("--isaac-python must be an executable Python file")
        key = args.key_file.expanduser().resolve()
        if key.is_relative_to(ROOT) or key.is_relative_to(policy):
            raise ValueError("Store the API key outside the source and policy directories")
        if not key.is_file() or not os.access(key, os.R_OK):
            raise ValueError("--key-file must be a readable external file")
        settings = load_settings(args.model_config)
        if args.model is not None:
            if not args.model.strip():
                raise ValueError("--model must not be empty")
            settings["model"] = args.model
        values = environment(settings, repo=repo, isaac_python=python, api_base=args.api_base,
                             key_file=key, sam3_url=args.sam3_url,
                             sim_cache=args.sim_cache, tmp_dir=args.tmp_dir)
        write_config(policy / "config.env", values)
    except (ValueError, OSError) as error:
        parser.exit(1, f"{error}\n")
    print(f"Wrote {policy / 'config.env'} (mode 0600; API key contents were not read)")


if __name__ == "__main__":
    main()
